#Requires -Version 5.1
<#
  Bounded, loopback-only MasterDrive smoke test for native Windows PowerShell 5.1.
  It never exports a real drive, configures Tailscale, or needs administrator rights.
#>
[CmdletBinding()]
param(
    [ValidateRange(1024, 65535)][int]$AgentPort = 18789,
    [ValidateRange(1024, 65535)][int]$ControllerPort = 18788
)

$ErrorActionPreference = 'Stop'
if ($AgentPort -eq $ControllerPort) { throw 'Agent and controller ports must differ.' }
if (-not (Get-Command 'go' -ErrorAction SilentlyContinue)) { throw 'Go is required.' }

$repoRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$webDir = Join-Path $repoRoot 'web'
if (-not (Test-Path -LiteralPath $webDir -PathType Container)) {
    throw 'Missing web/ UI; integrate the frontend before running the smoke test.'
}

function Assert-FreeLoopbackPort {
    param([Parameter(Mandatory)][int]$Port)
    $probe = [Net.Sockets.TcpListener]::new([Net.IPAddress]::Parse('127.0.0.1'), $Port)
    try {
        $probe.Start()
    } catch {
        throw "Loopback TCP port $Port is unavailable; choose an unused test port."
    } finally {
        $probe.Stop()
    }
}

function New-RandomToken {
    $bytes = New-Object byte[] 32
    $generator = [Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $generator.GetBytes($bytes)
    } finally {
        $generator.Dispose()
    }
    return [BitConverter]::ToString($bytes).Replace('-', '').ToLowerInvariant()
}

function Start-PrivateProcess {
    param(
        [Parameter(Mandatory)][string]$Executable,
        [Parameter(Mandatory)][string[]]$Arguments,
        [hashtable]$EnvironmentOverrides = @{}
    )
    $start = New-Object Diagnostics.ProcessStartInfo
    $start.FileName = $Executable
    $start.UseShellExecute = $false
    $start.CreateNoWindow = $true
    $start.RedirectStandardOutput = $true
    $start.RedirectStandardError = $true

    # Windows PowerShell 5.1 targets .NET Framework: ProcessStartInfo has no
    # ArgumentList or Environment property. These arguments are generated by
    # this test and contain neither literal quotes nor trailing backslashes.
    $quoted = foreach ($argument in $Arguments) {
        if ($argument.Contains('"') -or $argument.EndsWith('\')) {
            throw 'Unexpected process argument; refusing unsafe quoting.'
        }
        '"' + $argument + '"'
    }
    $start.Arguments = $quoted -join ' '
    foreach ($key in $EnvironmentOverrides.Keys) {
        $start.EnvironmentVariables[[string]$key] = [string]$EnvironmentOverrides[$key]
    }

    $process = [Diagnostics.Process]::Start($start)
    if ($null -eq $process) { throw 'Could not start a smoke-test child process.' }
    return $process
}

function Invoke-LoopbackRequest {
    param(
        [Parameter(Mandatory)][string]$Url,
        [ValidateSet('GET', 'POST')][string]$Method = 'GET',
        [hashtable]$Headers = @{},
        [Net.CookieContainer]$Cookies,
        [string]$OutputPath,
        [int]$TimeoutMs = 2000
    )
    # Bypass even system/user HTTP proxies; connect only to numeric loopback.
    $request = [Net.HttpWebRequest][Net.WebRequest]::Create($Url)
    if ($request.RequestUri.Host -ne '127.0.0.1') {
        throw 'Smoke requests are restricted to numeric IPv4 loopback.'
    }
    $request.Proxy = $null
    $request.AllowAutoRedirect = $false
    $request.Method = $Method
    $request.Timeout = $TimeoutMs
    $request.ReadWriteTimeout = $TimeoutMs
    if ($null -ne $Cookies) { $request.CookieContainer = $Cookies }
    foreach ($key in $Headers.Keys) { $request.Headers[[string]$key] = [string]$Headers[$key] }
    if ($Method -eq 'POST') { $request.ContentLength = 0 }

    $response = $null
    try {
        try {
            $response = [Net.HttpWebResponse]$request.GetResponse()
        } catch [Net.WebException] {
            # An HTTP 401 is an expected negative assertion, not a transport
            # failure. Connection errors still propagate to the bounded poll.
            if ($null -eq $_.Exception.Response) { throw }
            $response = [Net.HttpWebResponse]$_.Exception.Response
        }
        $status = [int]$response.StatusCode
        if ($status -eq 204 -or $status -eq 205) {
            return @{ StatusCode = $status; Body = '' }
        }
        $stream = $response.GetResponseStream()
        if ($null -eq $stream) {
            return @{ StatusCode = $status; Body = '' }
        }
        if (-not [string]::IsNullOrEmpty($OutputPath)) {
            if ($status -ne 200) { throw "Download returned HTTP $status." }
            $destination = [IO.File]::Open($OutputPath, [IO.FileMode]::CreateNew,
                [IO.FileAccess]::Write, [IO.FileShare]::None)
            try { $stream.CopyTo($destination) } finally { $destination.Dispose() }
            return @{ StatusCode = $status; Body = '' }
        }
        $reader = [IO.StreamReader]::new($stream, [Text.Encoding]::UTF8)
        try { $body = $reader.ReadToEnd() } finally { $reader.Dispose() }
        return @{ StatusCode = $status; Body = $body }
    } finally {
        if ($null -ne $response) { $response.Dispose() }
    }
}

function Wait-ForStatus {
    param(
        [Parameter(Mandatory)][string]$Url,
        [Parameter(Mandatory)][int]$ExpectedStatus,
        [Parameter(Mandatory)][Diagnostics.Process]$Process,
        [hashtable]$Headers = @{}
    )
    for ($attempt = 0; $attempt -lt 60; $attempt++) {
        if ($Process.HasExited) { throw 'A smoke-test child exited during startup.' }
        try {
            $result = Invoke-LoopbackRequest -Url $Url -Headers $Headers -TimeoutMs 1000
            if ($result.StatusCode -eq $ExpectedStatus) { return }
        } catch {
            # A listener may not have bound yet; only 60 attempts are allowed.
        }
        Start-Sleep -Milliseconds 100
    }
    throw 'A smoke-test child did not become ready on loopback.'
}

$tempParent = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\', '/')
$tempPath = Join-Path $tempParent ('masterdrive-ps51-' + [Guid]::NewGuid().ToString('N'))
$createdTemp = $false
$agentProcess = $null
$controllerProcess = $null
$passed = $false

try {
    Assert-FreeLoopbackPort -Port $AgentPort
    Assert-FreeLoopbackPort -Port $ControllerPort

    [void][IO.Directory]::CreateDirectory($tempPath)
    $createdTemp = $true
    $exportDir = Join-Path $tempPath 'export'
    $dataDir = Join-Path $tempPath 'state'
    [void][IO.Directory]::CreateDirectory($exportDir)
    [void][IO.Directory]::CreateDirectory($dataDir)
    $fixturePath = Join-Path $exportDir 'hello.txt'
    [IO.File]::WriteAllText($fixturePath, "MasterDrive PS5.1 smoke fixture`n",
        [Text.UTF8Encoding]::new($false))

    $token = New-RandomToken
    $binary = Join-Path $tempPath 'masterdrive.exe'
    Push-Location -LiteralPath $repoRoot
    try {
        & go build -o $binary ./cmd/masterdrive
        if ($LASTEXITCODE -ne 0) { throw 'Go build failed.' }
    } finally {
        Pop-Location
    }
    if (-not (Test-Path -LiteralPath $binary -PathType Leaf)) {
        throw 'Go build did not create the expected test executable.'
    }

    $agentAddress = "127.0.0.1:$AgentPort"
    $controllerAddress = "127.0.0.1:$ControllerPort"
    $agentProcess = Start-PrivateProcess -Executable $binary `
        -Arguments @('agent', '-listen', $agentAddress, '-export', "smoke=$exportDir") `
        -EnvironmentOverrides @{ MASTERDRIVE_AGENT_TOKEN = $token }
    Wait-ForStatus -Url "http://$agentAddress/v1/shares" -ExpectedStatus 200 `
        -Process $agentProcess -Headers @{ Authorization = "Bearer $token" }

    $registration = @(& $binary add-host -data-dir $dataDir -name smoke-node `
        -url "http://$agentAddress")
    if ($LASTEXITCODE -ne 0 -or $registration.Count -lt 1) {
        throw 'Host registration failed or returned no host ID.'
    }
    $match = [regex]::Match([string]$registration[0], '^Added .+: ([0-9a-f]{32})$')
    if (-not $match.Success) { throw 'Host registration returned an unexpected ID.' }
    $hostId = $match.Groups[1].Value
    $tokenMap = @{}
    $tokenMap[$hostId] = $token
    $tokenJson = ConvertTo-Json -InputObject $tokenMap -Compress

    $controllerProcess = Start-PrivateProcess -Executable $binary `
        -Arguments @('controller', '-listen', $controllerAddress, '-data-dir', $dataDir,
                     '-web-dir', $webDir) `
        -EnvironmentOverrides @{ MASTERDRIVE_PEER_TOKENS_JSON = $tokenJson }

    # ReadLine() can wait forever if startup fails. Race its async equivalent
    # against a ten-second deadline; never echo the URL's session fragment.
    $lineTask = $controllerProcess.StandardOutput.ReadLineAsync()
    $taskList = [Threading.Tasks.Task[]]@($lineTask, [Threading.Tasks.Task]::Delay(10000))
    $completed = [Threading.Tasks.Task]::WhenAny($taskList).GetAwaiter().GetResult()
    if (-not [object]::ReferenceEquals($completed, $lineTask)) {
        throw 'Controller did not emit its session URL within ten seconds.'
    }
    $launchLine = $lineTask.GetAwaiter().GetResult()
    if ($controllerProcess.HasExited) { throw 'Controller exited during startup.' }
    $sessionMatch = [regex]::Match([string]$launchLine, '#session=([A-Za-z0-9_-]{40,})$')
    if (-not $sessionMatch.Success) { throw 'Controller emitted no usable local session.' }
    $sessionToken = $sessionMatch.Groups[1].Value
    $controllerBase = "http://$controllerAddress"

    # This must remain unauthorized before a browser session is activated.
    Wait-ForStatus -Url "$controllerBase/api/v1/hosts" -ExpectedStatus 401 `
        -Process $controllerProcess

    $cookies = New-Object Net.CookieContainer
    $activation = Invoke-LoopbackRequest -Url "$controllerBase/api/v1/session" -Method POST `
        -Headers @{ 'X-MasterDrive-Session' = $sessionToken } -Cookies $cookies
    if ($activation.StatusCode -ne 204) { throw 'Local session activation failed.' }
    if ($cookies.GetCookies([Uri]"$controllerBase/api/v1/hosts").Count -lt 1) {
        throw 'Session activation did not set a cookie.'
    }

    $hostsReply = Invoke-LoopbackRequest -Url "$controllerBase/api/v1/hosts" -Cookies $cookies
    $sharesReply = Invoke-LoopbackRequest -Url "$controllerBase/api/v1/hosts/$hostId/shares" `
        -Cookies $cookies
    $entriesReply = Invoke-LoopbackRequest `
        -Url "$controllerBase/api/v1/hosts/$hostId/shares/smoke/entries" -Cookies $cookies
    if ($hostsReply.StatusCode -ne 200 -or $sharesReply.StatusCode -ne 200 -or
        $entriesReply.StatusCode -ne 200) {
        throw 'Authenticated catalog or listing request failed.'
    }
    $hosts = $hostsReply.Body | ConvertFrom-Json
    $shares = $sharesReply.Body | ConvertFrom-Json
    $entries = $entriesReply.Body | ConvertFrom-Json
    if (@($hosts.hosts | Where-Object { $_.id -eq $hostId }).Count -ne 1 -or
        @($shares.shares | Where-Object { $_.id -eq 'smoke' }).Count -ne 1 -or
        @($entries.entries | Where-Object { $_.name -eq 'hello.txt' }).Count -ne 1) {
        throw 'Registered host, exported share, or fixture was missing.'
    }

    $downloadPath = Join-Path $tempPath 'downloaded.txt'
    $download = Invoke-LoopbackRequest `
        -Url "$controllerBase/api/v1/hosts/$hostId/shares/smoke/download?path=hello.txt" `
        -Cookies $cookies -OutputPath $downloadPath -TimeoutMs 10000
    if ($download.StatusCode -ne 200 -or
        (Get-FileHash -LiteralPath $fixturePath -Algorithm SHA256).Hash -ne
        (Get-FileHash -LiteralPath $downloadPath -Algorithm SHA256).Hash) {
        throw 'Downloaded fixture bytes do not match the temporary export.'
    }

    $passed = $true
} finally {
    # Kill precisely the process objects launched above, not names or ports.
    foreach ($process in @($controllerProcess, $agentProcess)) {
        if ($null -eq $process) { continue }
        try {
            if (-not $process.HasExited) {
                $process.Kill()
                [void]$process.WaitForExit(5000)
            }
        } finally {
            $process.Dispose()
        }
    }

    if ($createdTemp -and (Test-Path -LiteralPath $tempPath -PathType Container)) {
        $fullPath = [IO.Path]::GetFullPath($tempPath)
        $leaf = [IO.Path]::GetFileName($fullPath)
        $exactParent = [IO.Path]::GetDirectoryName($fullPath).TrimEnd('\', '/')
        if ($exactParent -ne $tempParent -or $leaf -cnotmatch '^masterdrive-ps51-[0-9a-f]{32}$') {
            throw 'Refusing to clean an unexpected temporary directory.'
        }
        # Never recursively remove a path on Windows PowerShell 5.1: a nested
        # junction could redirect deletion outside this disposable fixture.
        # Delete only these exact expected files, then empty directories.
        $files = @(
            (Join-Path $fullPath 'export\hello.txt'),
            (Join-Path $fullPath 'state\hosts.json'),
            (Join-Path $fullPath 'state\hosts.json.lock'),
            (Join-Path $fullPath 'masterdrive.exe'),
            (Join-Path $fullPath 'downloaded.txt')
        )
        foreach ($filePath in $files) {
            if ([IO.File]::Exists($filePath)) {
                if (([IO.File]::GetAttributes($filePath) -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
                    throw 'Refusing to remove a reparse-point fixture file.'
                }
                [IO.File]::Delete($filePath)
            }
        }
        foreach ($directoryPath in @((Join-Path $fullPath 'export'), (Join-Path $fullPath 'state'), $fullPath)) {
            if ([IO.Directory]::Exists($directoryPath)) {
                if (([IO.File]::GetAttributes($directoryPath) -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
                    throw 'Refusing to remove a reparse-point fixture directory.'
                }
                [IO.Directory]::Delete($directoryPath, $false)
            }
        }
    }
}
if ($passed) {
    Write-Output 'PASS: WinPS5.1 loopback agent, registration, session cookie, listing, and download.'
}
